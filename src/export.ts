import { basename } from "node:path";
import type { State } from "./fold.js";
import { CAT_LABEL, STATUS_LABEL, live, questionsForUser, verificationLine } from "./report.js";
import type { AnyEvent, Category, Dep, QOption, SlotKey } from "./types.js";

export const EXPORT_FORMATS = ["markdown", "json"] as const;
export type ExportFormat = (typeof EXPORT_FORMATS)[number];

/**
 * Project state for a shared team doc (Notion and the like). Every entry carries a stable id
 * (slot key, question id, task slug) so the AI can overwrite the doc entry by entry, and asOf
 * names the last event so a later read can tell which state the doc was synced from.
 */
export interface Export {
  project: string;
  asOf: { event: string; at: string } | null;
  decisions: {
    key: SlotKey;
    category: Category;
    version: number;
    value: string;
    rationale: string;
    status: string;
    source: "user" | "AI";
    updatedAt: string;
    depends: (Dep & { current: number })[];
    scope?: string[];
    userQuote?: string;
    history: { n: number; value: string; status: string; retired?: boolean }[];
  }[];
  questions: { id: string; text: string; about: SlotKey[]; options?: QOption[]; askedAt: string }[];
  tasks: {
    slug: string;
    title: string;
    status: string;
    note?: string;
    verification: string;
    needsReview: SlotKey[];
    waitingOn?: SlotKey[];
    /** Why it's on hold */
    suspended?: string;
    handoff?: { text: string; writtenAt: string; changedSince: SlotKey[] };
  }[];
}

const date = (s: string) => s.slice(0, 16).replace("T", " ") + " UTC";

export function buildExport(state: State, events: AnyEvent[], root: string): Export {
  const last = events.at(-1);
  const currentN = (k: SlotKey) => state.slots.get(k)?.current?.n ?? 0;
  return {
    project: basename(root),
    asOf: last ? { event: last.id, at: last.at } : null,
    decisions: live(state).map((s) => {
      const v = s.current!;
      return {
        key: s.key,
        category: s.category,
        version: v.n,
        value: v.value,
        rationale: v.rationale,
        status: STATUS_LABEL[v.status],
        source: v.source === "user" ? "user" : "AI",
        updatedAt: v.at,
        depends: v.depends.map((d) => ({ ...d, current: currentN(d.key) })),
        ...(v.scope?.length ? { scope: v.scope } : {}),
        ...(v.userQuote ? { userQuote: v.userQuote } : {}),
        history: s.versions.slice(s.liveFrom).map((h) => ({ n: h.n, value: h.value, status: STATUS_LABEL[h.status], ...(h.retired ? { retired: true } : {}) })),
      };
    }),
    questions: questionsForUser(state).map((q) => ({ id: q.qid, text: q.text, about: q.about, ...(q.options?.length ? { options: q.options } : {}), askedAt: q.at })),
    tasks: [...state.tasks.values()]
      .filter((t) => t.lifecycle !== "archived" && t.status !== "dropped")
      .map((t) => ({
        slug: t.slug,
        title: t.title,
        status: t.status,
        ...(t.note ? { note: t.note } : {}),
        verification: verificationLine(t),
        needsReview: t.needsReview.map((d) => d.key),
        ...(t.waitingOn.length ? { waitingOn: t.waitingOn } : {}),
        ...(t.lifecycle === "suspended" ? { suspended: t.lifecycleNote?.note ?? "" } : {}),
        ...(t.handoff ? { handoff: { text: t.handoff.text, writtenAt: date(t.handoff.at), changedSince: t.handoff.changed.map((d) => d.key) } } : {}),
      })),
  };
}

export function renderExportMd(x: Export): string {
  const one = (s: string) => s.replace(/\s*\n\s*/g, " ");
  const asOf = x.asOf ? `${date(x.asOf.at)} (event ${x.asOf.event})` : "no events yet";
  const out: string[] = [
    `# ${x.project}: project state`,
    "",
    `> Generated by slotledger as of ${asOf}. The next sync overwrites any edits made here, so leave a comment instead; your AI records it in slotledger.`,
  ];

  out.push("", "## Decisions");
  if (!x.decisions.length) out.push("", "(none)");
  for (const d of x.decisions) {
    out.push("", `### ${d.key}`, "", `- Value: ${one(d.value)}`);
    out.push(`- Status: ${d.status} · v${d.version} · by ${d.source} · ${CAT_LABEL[d.category]} · updated ${date(d.updatedAt)}`);
    out.push(`- Rationale: ${one(d.rationale)}`);
    if (d.depends.length) {
      out.push(`- Depends on: ${d.depends.map((p) => `${p.key} v${p.n}${p.current !== p.n ? ` ⚠ premise changed (now ${p.current ? `v${p.current}` : "gone"})` : ""}`).join(", ")}`);
    }
    if (d.scope) out.push(`- Scope: ${d.scope.join(", ")}`);
    if (d.userQuote) out.push(`- User's words: "${one(d.userQuote)}"`);
    if (d.history.length > 1) {
      out.push(`- History: ${d.history.map((h) => `v${h.n} "${one(h.value)}"${h.retired ? " (retired)" : ""}${h.status === STATUS_LABEL.rejected ? " (rejected)" : ""}`).join(" → ")}`);
    }
  }

  out.push("", "## Questions waiting on the team");
  if (!x.questions.length) out.push("", "(none)");
  for (const q of x.questions) {
    out.push("", `### ${q.id}`, "", one(q.text), "");
    if (q.options) out.push(`- Options: ${q.options.map((o) => `${o.id} ${o.label}${o.recommended ? " (recommended)" : ""}`).join(" / ")}`);
    out.push(`- About: ${q.about.join(", ")}`, `- Asked: ${date(q.askedAt)}`);
  }

  out.push("", "## Tasks");
  if (!x.tasks.length) out.push("", "(none)");
  for (const t of x.tasks) {
    out.push("", `### ${t.slug}`, "", `- Title: ${one(t.title)}`, `- Status: ${t.status}${t.status === "needs_review" ? ` (${t.needsReview.join(", ")} changed)` : t.waitingOn?.length ? ` (waiting on review of ${t.waitingOn.join(", ")})` : ""}`);
    out.push(`- Verification: ${t.verification}`);
    if (t.suspended !== undefined) out.push(`- Suspended: ${one(t.suspended)}`);
    if (t.note) out.push(`- Note: ${one(t.note)}`);
    if (t.handoff) {
      out.push(`- Handoff (written ${t.handoff.writtenAt}${t.handoff.changedSince.length ? `; changed since: ${t.handoff.changedSince.join(", ")}` : ""}):`, "");
      out.push(...t.handoff.text.split("\n").map((l) => `  > ${l}`));
    }
  }
  return out.join("\n") + "\n";
}

export function renderExport(x: Export, format: ExportFormat): string {
  return format === "json" ? JSON.stringify(x, null, 2) + "\n" : renderExportMd(x);
}
